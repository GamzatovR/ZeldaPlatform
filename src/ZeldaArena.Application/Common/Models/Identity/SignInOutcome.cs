namespace ZeldaArena.Application.Common.Models.Identity;

/// <summary>
/// Чем закончилась попытка входа. Отдельный тип вместо bool: страницы входа обязаны
/// развести четыре разных продолжения — форму второго фактора, страницу блокировки,
/// предложение подтвердить почту и сообщение об ошибке (docs/SPEC.md §8.2).
///
/// Причина неудачи пользователю не уточняется намеренно: «неверный логин или пароль»
/// одинаково отвечает и на несуществующий адрес, и на неверный пароль — иначе форма
/// превращается в средство перебора существующих адресов.
/// </summary>
public enum SignInOutcome
{
    /// <summary>Пара логин-пароль не подошла.</summary>
    Failed = 0,

    Succeeded = 1,

    /// <summary>Пароль верен, включена 2FA — нужен код из аутентификатора.</summary>
    RequiresTwoFactor = 2,

    /// <summary>Сработал lockout: 5 неудачных попыток, 15 минут ожидания (§8.2).</summary>
    LockedOut = 3,

    /// <summary>Вход запрещён — как правило, не подтверждён email.</summary>
    NotAllowed = 4,
}