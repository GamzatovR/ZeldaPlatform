namespace ZeldaArena.Application.Common.Interfaces;

/// <summary>
/// Анонимный идентификатор гостевой корзины (docs/SPEC.md §14.1). Выдаёт и проверяет
/// его <c>CartCookieMiddleware</c> по подписанной куке; сюда он попадает уже проверенным.
///
/// Порт, а не параметр команды: владельца корзины определяет сервер, а не запрос.
/// Команды корзины не принимают ни идентификатора корзины, ни идентификатора гостя,
/// поэтому подставить чужую корзину нечем — защита от IDOR по построению (§15).
///
/// Реализация живёт в Web, как у <see cref="IAccountEmailSender"/>: кука — знание
/// слоя представления.
/// </summary>
public interface IGuestCartIdentity
{
    /// <summary>Проверенный идентификатор гостя или <c>null</c>, если куки нет или она подделана.</summary>
    Guid? AnonymousId { get; }
}