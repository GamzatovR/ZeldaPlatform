using ZeldaArena.Application.Common.Models.Billing;

namespace ZeldaArena.Application.Common.Interfaces;

/// <summary>
/// Выпуск и хеширование кода подтверждения оплаты (docs/SPEC.md §7.6).
///
/// Порт, а не статический помощник в Application, по двум причинам. Во-первых,
/// выпуск случаен, и без подмены реализации сценарий подтверждения не проверить тестом.
/// Во-вторых, хеш берётся с перцем из конфигурации: шестизначный код — это миллион
/// вариантов, и голый SHA-256 по дампу базы перебирается за секунды, а конфигурация
/// в Application недоступна.
///
/// Сам код наружу выходит ровно один раз — в письмо. Ни в базу, ни в логи, ни в аудит
/// он не попадает: в <c>Payments</c> хранится только хеш (§7.6, §13).
/// </summary>
public interface IConfirmationCodeProtector
{
    /// <summary>Новый код и его хеш. Код отдаётся вызывающему только чтобы отправить письмо.</summary>
    ConfirmationCode Issue();

    /// <summary>
    /// Хеш введённого пользователем кода — его и сверяет <c>Payment.Confirm</c>
    /// сравнением постоянного времени.
    /// </summary>
    string Hash(string code);
}