namespace ZeldaArena.Application.Features.Payments;

/// <summary>
/// Ключ идемпотентности платежа (docs/SPEC.md §7.6).
///
/// Ключ приходит скрытым полем формы, то есть полностью подконтролен клиенту,
/// а уникальный индекс на <c>Payments.IdempotencyKey</c> — общий на всю таблицу (§6).
/// Из-за этого чужой ключ, поданный вторым пользователем, ронял вставку на нарушении
/// уникальности: поиск шёл по паре «пользователь + ключ» и существующий платёж
/// не находил. Поймано пробой на живом приложении.
///
/// Поэтому в базу уходит не сам ключ, а пара «пользователь : ключ». Одинаковые ключи
/// у разных людей теперь невозможны по построению, а не по договорённости, и глобальный
/// индекс продолжает делать ровно то, ради чего заведён: защищать от повторной
/// отправки одной и той же формы.
/// </summary>
public static class PaymentIdempotency
{
    /// <summary>
    /// Сколько отводится клиентской части. Форма присылает Guid (36 символов),
    /// а в столбце 80: 32 на идентификатор пользователя, один на разделитель
    /// и остаток — на ключ.
    /// </summary>
    public const int MaxClientKeyLength = 40;

    private const char Separator = ':';

    public static string KeyFor(Guid userId, string clientKey)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(clientKey);

        return $"{userId:N}{Separator}{clientKey.Trim()}";
    }
}